// --- Attack arc tiles (3 tiles in front based on direction) ---
function getAttackTiles() {
    const { x, y, direction } = player;
    if (direction === 'up')    return [{x: x-1, y: y-1}, {x, y: y-1}, {x: x+1, y: y-1}];
    if (direction === 'down')  return [{x: x-1, y: y+1}, {x, y: y+1}, {x: x+1, y: y+1}];
    if (direction === 'left')  return [{x: x-1, y: y-1}, {x: x-1, y}, {x: x-1, y: y+1}];
    if (direction === 'right') return [{x: x+1, y: y-1}, {x: x+1, y}, {x: x+1, y: y+1}];
    return [];
}

// --- Spawn enemies on walkable tiles away from player ---
function spawnEnemies(count) {
    const spawned = [];
    let attempts = 0;
    while (spawned.length < count && attempts < 5000) {
        attempts++;
        const ex = Math.floor(Math.random() * mapCols);
        const ey = Math.floor(Math.random() * mapRows);
        const dist = Math.abs(ex - player.x) + Math.abs(ey - player.y);
        if (dist < 8) continue;
        if (!canMove(ex, ey)) continue;
        if (spawned.some(e => e.x === ex && e.y === ey)) continue;
        spawned.push({ x: ex, y: ey, px: ex * tileSize, py: ey * tileSize,
                       hp: 30, maxHp: 30, moveTick: 0, moveInterval: 90 + Math.floor(Math.random() * 60) });
    }
    return spawned;
}

let enemies = spawnEnemies(20);
let attackSwingTiles = [];

function isWall(nx, ny) {
    if (ny < 0 || ny >= map.length || nx < 0 || nx >= map[0].length) return false;
    return map[ny][nx] === 1;
}

function canMove(nx, ny) {
    if (nx < 0 || ny < 0 || nx >= mapCols || ny >= mapRows) return false;
    if (isWall(nx, ny)) return false;
    return true;
}

function startMove(dx, dy, direction) {
    if (player.moving) return;
    const nx = player.x + dx;
    const ny = player.y + dy;
    if (!canMove(nx, ny)) return;
    player.targetX = nx;
    player.targetY = ny;
    player.direction = direction;
    player.moving = true;
}

function handleInput() {
    if (player.moving) return;

    if (input.ArrowUp) startMove(0, -1, 'up');
    else if (input.ArrowDown) startMove(0, 1, 'down');
    else if (input.ArrowLeft) startMove(-1, 0, 'left');
    else if (input.ArrowRight) startMove(1, 0, 'right');

    savePlayer();
}

function doAttack() {
    if (player.attacking) return;
    if (player.moving) return;
    if (player.attackCooldown > 0) return;

    player.attacking = true;
    player.attackFrame = 0;
    attackSwingTiles = getAttackTiles();

    // Hit enemies in attack tiles
    const hitTiles = new Set(attackSwingTiles.map(t => t.x + ',' + t.y));
    enemies.forEach(e => {
        if (hitTiles.has(e.x + ',' + e.y)) {
            e.hp -= 25;
        }
    });
    enemies = enemies.filter(e => e.hp > 0);
}

function getCSRFToken() {
    return document.cookie
        .split('; ')
        .find(row => row.startsWith('csrftoken='))
        ?.split('=')[1];
}

function savePlayer() {
    fetch("/save/", {
        method: "POST",
        headers: {
            "Content-Type": "application/json",
            "X-CSRFToken": getCSRFToken()
        },
        body: JSON.stringify(player)
    });
}

function update() {
    handleInput();

    if (player.moving) {
        const targetPx = player.targetX * tileSize;
        const targetPy = player.targetY * tileSize;

        if (player.px < targetPx) player.px += player.speed;
        if (player.px > targetPx) player.px -= player.speed;
        if (player.py < targetPy) player.py += player.speed;
        if (player.py > targetPy) player.py -= player.speed;

        if (player.px === targetPx && player.py === targetPy) {
            player.x = player.targetX;
            player.y = player.targetY;
            player.moving = false;
        }
    }

    // Tick attack animation
    if (player.attacking) {
        player.attackFrame++;
        if (player.attackFrame >= player.attackDuration) {
            player.attacking = false;
            attackSwingTiles = [];
            player.attackCooldown = player.attackCooldownMax;
        }
    }

    // Tick cooldown down
    if (player.attackCooldown > 0) {
        player.attackCooldown--;
    }

    // Enemy AI — move toward player every moveInterval frames
    enemies.forEach(e => {
        e.moveTick++;
        if (e.moveTick < e.moveInterval) return;
        e.moveTick = 0;

        const dx = player.x - e.x;
        const dy = player.y - e.y;
        // Pick the axis with bigger distance
        const steps = [];
        if (Math.abs(dx) >= Math.abs(dy)) {
            steps.push([Math.sign(dx), 0]);
            steps.push([0, Math.sign(dy)]);
        } else {
            steps.push([0, Math.sign(dy)]);
            steps.push([Math.sign(dx), 0]);
        }
        for (const [sx, sy] of steps) {
            if (sx === 0 && sy === 0) continue;
            const nx = e.x + sx, ny = e.y + sy;
            const occupied = enemies.some(other => other !== e && other.x === nx && other.y === ny);
            if (canMove(nx, ny) && !occupied) {
                e.x = nx; e.y = ny;
                e.px = nx * tileSize; e.py = ny * tileSize;
                break;
            }
        }

        // Damage player if on same tile
        if (e.x === player.x && e.y === player.y) {
            player.hp = Math.max(0, player.hp - 10);
        }
    });

    // Update camera every frame so it smoothly follows during movement
    updateCamera();

    draw();
    requestAnimationFrame(update);
}

function drawGrid() {
    // Deep forest void outside map
    ctx.fillStyle = '#0d1a0d';
    ctx.fillRect(0, 0, canvas.width, canvas.height);

    const startCol = Math.floor(camera.x / tileSize) - 1;
    const startRow = Math.floor(camera.y / tileSize) - 1;
    const endCol = startCol + Math.ceil(canvas.width / tileSize) + 2;
    const endRow = startRow + Math.ceil(canvas.height / tileSize) + 2;

    for (let row = startRow; row <= endRow; row++) {
        for (let col = startCol; col <= endCol; col++) {
            const screenX = col * tileSize - camera.x;
            const screenY = row * tileSize - camera.y;

            // Outside world — mossy void
            if (col < 0 || row < 0 || col >= mapCols || row >= mapRows) {
                ctx.fillStyle = '#0d1a0d';
                ctx.fillRect(screenX, screenY, tileSize, tileSize);
                continue;
            }

            const tileVal = map[row][col];

            if (tileVal === 1) {
                // Tree tile — dark green canopy with trunk detail
                ctx.fillStyle = '#1a3d1a';
                ctx.fillRect(screenX, screenY, tileSize, tileSize);

                // Canopy top highlight
                ctx.fillStyle = '#2d6e2d';
                ctx.fillRect(screenX + 2, screenY + 2, tileSize - 4, 10);

                // Canopy body
                ctx.fillStyle = '#245224';
                ctx.fillRect(screenX + 4, screenY + 10, tileSize - 8, 10);

                // Trunk
                ctx.fillStyle = '#5c3a1e';
                ctx.fillRect(screenX + tileSize/2 - 3, screenY + 18, 6, tileSize - 20);

                // Dark canopy shadow on bottom-right
                ctx.fillStyle = '#122612';
                ctx.fillRect(screenX + tileSize - 6, screenY + 4, 4, tileSize - 8);
                ctx.fillRect(screenX + 4, screenY + tileSize - 6, tileSize - 8, 4);
            } else {
                // Forest floor — alternating grass patches
                const shade = (row + col) % 2 === 0 ? '#4a8c4a' : '#52995a';
                ctx.fillStyle = shade;
                ctx.fillRect(screenX, screenY, tileSize, tileSize);

                // Subtle grass texture dots
                ctx.fillStyle = (row + col) % 2 === 0 ? '#3d7a3d' : '#469146';
                ctx.fillRect(screenX + 6, screenY + 8, 2, 4);
                ctx.fillRect(screenX + 14, screenY + 18, 2, 4);
                ctx.fillRect(screenX + 22, screenY + 6, 2, 4);

                // Path-like border (very subtle)
                ctx.strokeStyle = '#3d7a3d';
                ctx.lineWidth = 0.3;
                ctx.strokeRect(screenX, screenY, tileSize, tileSize);
            }
        }
    }

    // Forest edge border — thick dark tree-line glow
    const mapPixelW = mapCols * tileSize;
    const mapPixelH = mapRows * tileSize;
    const edgeX = -camera.x;
    const edgeY = -camera.y;

    ctx.strokeStyle = '#1a5c1a';
    ctx.lineWidth = 6;
    ctx.shadowColor = '#00ff44';
    ctx.shadowBlur = 16;
    ctx.strokeRect(edgeX, edgeY, mapPixelW, mapPixelH);
    ctx.shadowBlur = 0;
    ctx.lineWidth = 1;
}

function drawPlayer() {
    // Player is always drawn at the center of the canvas
    const screenX = canvas.width / 2 - tileSize / 2;
    const screenY = canvas.height / 2 - tileSize / 2;

    ctx.fillStyle = '#ffdd55';
    ctx.fillRect(screenX + 4, screenY + 4, tileSize - 8, tileSize - 8);

    ctx.fillStyle = '#333';
    const eyeX = screenX + (player.direction === 'left' ? 8 : player.direction === 'right' ? 18 : 12);
    const eyeY = screenY + (player.direction === 'up' ? 10 : player.direction === 'down' ? 18 : 12);
    ctx.beginPath();
    ctx.arc(eyeX, eyeY, 3, 0, 2 * Math.PI);
    ctx.fill();
}

function drawEnemies() {
    enemies.forEach(e => {
        const sx = e.x * tileSize - camera.x;
        const sy = e.y * tileSize - camera.y;
        // Cull off-screen
        if (sx < -tileSize || sy < -tileSize || sx > canvas.width || sy > canvas.height) return;

        // Body
        ctx.fillStyle = '#cc2222';
        ctx.fillRect(sx + 4, sy + 4, tileSize - 8, tileSize - 8);

        // Eyes
        ctx.fillStyle = '#ffff00';
        ctx.beginPath();
        ctx.arc(sx + 10, sy + 11, 3, 0, Math.PI * 2);
        ctx.fill();
        ctx.beginPath();
        ctx.arc(sx + 22, sy + 11, 3, 0, Math.PI * 2);
        ctx.fill();

        // HP bar background
        ctx.fillStyle = '#550000';
        ctx.fillRect(sx + 2, sy - 6, tileSize - 4, 4);
        // HP bar fill
        ctx.fillStyle = '#ff3333';
        ctx.fillRect(sx + 2, sy - 6, (tileSize - 4) * (e.hp / e.maxHp), 4);
    });
}

function drawAttackArc() {
    if (!player.attacking || attackSwingTiles.length === 0) return;
    // Fade in then out over attackDuration frames
    const progress = player.attackFrame / player.attackDuration;
    const alpha = progress < 0.4 ? progress / 0.4 : 1 - (progress - 0.4) / 0.6;
    const centerX = canvas.width / 2 - tileSize / 2;
    const centerY = canvas.height / 2 - tileSize / 2;

    attackSwingTiles.forEach((t, i) => {
        const offsetX = (t.x - player.x) * tileSize;
        const offsetY = (t.y - player.y) * tileSize;
        const sx = centerX + offsetX;
        const sy = centerY + offsetY;

        // Swing slash arc tile
        ctx.save();
        ctx.globalAlpha = alpha * 0.75;
        ctx.fillStyle = '#ffdd55';
        ctx.fillRect(sx + 2, sy + 2, tileSize - 4, tileSize - 4);

        // Slash line across tile
        ctx.strokeStyle = '#ffffff';
        ctx.lineWidth = 2;
        ctx.beginPath();
        if (player.direction === 'up' || player.direction === 'down') {
            ctx.moveTo(sx + 4, sy + tileSize / 2);
            ctx.lineTo(sx + tileSize - 4, sy + tileSize / 2);
        } else {
            ctx.moveTo(sx + tileSize / 2, sy + 4);
            ctx.lineTo(sx + tileSize / 2, sy + tileSize - 4);
        }
        ctx.stroke();
        ctx.restore();
    });
}

function drawHUD() {
    const barW = 180, barH = 18, barX = 16, barY = 16;

    // HP bar background
    ctx.fillStyle = '#1a0000';
    ctx.fillRect(barX, barY, barW, barH);

    // HP bar fill — green to red based on %
    const pct = player.hp / player.maxHp;
    ctx.fillStyle = pct > 0.5 ? '#22cc44' : pct > 0.25 ? '#ddaa00' : '#cc2222';
    ctx.fillRect(barX, barY, barW * pct, barH);

    // HP bar border
    ctx.strokeStyle = '#ffffff';
    ctx.lineWidth = 1.5;
    ctx.strokeRect(barX, barY, barW, barH);

    // HP text
    ctx.fillStyle = '#ffffff';
    ctx.font = 'bold 12px monospace';
    ctx.fillText('HP ' + player.hp + ' / ' + player.maxHp, barX + 6, barY + 13);

    // Attack hint + cooldown bar
    const onCooldown = player.attackCooldown > 0;
    const cantAttack = player.moving || onCooldown || player.attacking;
    ctx.fillStyle = cantAttack ? '#666666' : '#ffdd55';
    ctx.font = '11px monospace';
    const hintText = player.attacking ? 'Attacking...' : onCooldown ? 'Cooldown...' : player.moving ? 'Can\'t attack (moving)' : '[SPACE] Attack';
    ctx.fillText(hintText, barX, barY + barH + 14);

    // Cooldown bar
    if (onCooldown || player.attacking) {
        const cdW = barW;
        const cdPct = player.attacking
            ? 1
            : player.attackCooldown / player.attackCooldownMax;
        ctx.fillStyle = '#222222';
        ctx.fillRect(barX, barY + barH + 18, cdW, 5);
        ctx.fillStyle = player.attacking ? '#ffdd55' : '#ff8800';
        ctx.fillRect(barX, barY + barH + 18, cdW * cdPct, 5);
        ctx.strokeStyle = '#555555';
        ctx.lineWidth = 1;
        ctx.strokeRect(barX, barY + barH + 18, cdW, 5);
    }
}

function draw() {
    drawGrid();
    drawAttackArc();
    drawEnemies();
    drawPlayer();
    drawHUD();
}

